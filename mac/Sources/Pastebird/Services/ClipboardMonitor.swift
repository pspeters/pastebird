import AppKit

/// Watches the general pasteboard and reports new text (with its formatting), URLs, file lists and images.
/// macOS has no "clipboard changed" notification, so it checks the change count a few times per second,
/// which costs next to nothing. Content that password managers mark as private is skipped (nspasteboard.org).
final class ClipboardMonitor {
    private static let maxChars = 200_000
    private static let maxFormattingChars = 2_000_000

    /// Types that mean "don't record this" (password managers, generated or transient content).
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    private let pasteboard = NSPasteboard.general
    private var timer: Timer?
    private var lastChangeCount: Int
    private var ownChangeCount = -1
    private let imageQueue = DispatchQueue(label: "Pastebird.images", qos: .utility)

    /// Called with a new item (not yet in the history) and its formatting or image, if any.
    var captured: ((ClipItem, ClipData?) -> Void)?

    init() {
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.25, repeats: true) { [weak self] _ in self?.poll() }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Puts an item back on the clipboard: text with its formatting unless `keepFormatting` is false,
    /// images as PNG and TIFF (or their recognized text when `keepFormatting` is false),
    /// and file lists as real files when they still exist.
    func setClipboard(_ item: ClipItem, stored: ClipData?, keepFormatting: Bool) throws {
        var items: [NSPasteboardItem] = []
        let first = NSPasteboardItem()
        items.append(first)

        if item.kind == .image && !keepFormatting && !(item.imageText ?? "").isEmpty {
            first.setString(item.imageText!, forType: .string) // ⌘↩: the text in the image
        } else if item.kind == .image {
            guard let png = stored?.png else { throw CocoaError(.fileReadNoSuchFile) }
            first.setData(png, forType: .png)
            if let tiff = ClipImages.tiff(png) { first.setData(tiff, forType: .tiff) }
        } else if item.kind == .files, case let files = item.files,
                  files.allSatisfy({ FileManager.default.fileExists(atPath: $0) }) {
            // One pasteboard item per file, as Finder does; the first one also carries the paths as text.
            for (i, path) in files.enumerated() {
                let entry = i == 0 ? first : NSPasteboardItem()
                entry.setString(URL(fileURLWithPath: path).absoluteString, forType: .fileURL)
                if i > 0 { items.append(entry) }
            }
            first.setString(item.content, forType: .string)
        } else {
            if keepFormatting, let stored {
                if let html = stored.html { first.setString(html, forType: .html) }
                if let rtf = stored.rtf { first.setData(rtf, forType: .rtf) }
            }
            first.setString(item.content, forType: .string)
        }

        pasteboard.clearContents()
        guard pasteboard.writeObjects(items) else { throw CocoaError(.fileWriteUnknown) }
        ownChangeCount = pasteboard.changeCount
        lastChangeCount = ownChangeCount
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        // Apps sometimes write the pasteboard in several steps; read once they're done.
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.06) { [weak self] in
            guard let self, self.pasteboard.changeCount == count, count != self.ownChangeCount else { return }
            self.read()
        }
    }

    private func read() {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        if types.isEmpty || !types.isDisjoint(with: Self.ignoredTypes) { return }

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let paths = urls.map(\.path)
            captured?(ClipItem(content: paths.joined(separator: "\n"), kind: .files), nil)
        } else if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            // Text wins over an image: apps like Excel and Word also put a picture of copied text on the pasteboard.
            if text.count > Self.maxChars { return }
            let formatting = readFormatting()
            captured?(ClipItem(content: text, kind: ClipItem.detectKind(text), hasFormatting: formatting != nil), formatting)
        } else if let image = ClipImages.read(pasteboard) {
            // Encoding a large screenshot and its thumbnail takes a moment; don't block the UI.
            imageQueue.async { [weak self] in
                guard let (item, data) = ClipImages.create(image) else { return }
                DispatchQueue.main.async { self?.captured?(item, data) }
            }
        }
    }

    private func readFormatting() -> ClipData? {
        var html = pasteboard.string(forType: .html)
        if let h = html, h.isEmpty || h.count > Self.maxFormattingChars { html = nil }
        var rtf = pasteboard.data(forType: .rtf)
        if let r = rtf, r.isEmpty || r.count > Self.maxFormattingChars { rtf = nil }
        return html == nil && rtf == nil ? nil : ClipData(html: html, rtf: rtf)
    }
}
